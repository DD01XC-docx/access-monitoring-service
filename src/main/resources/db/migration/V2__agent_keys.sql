-- API keys for AI agents. Only a SHA-256 of the secret part is stored; the full key is shown once.

CREATE TABLE agent_keys (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name          varchar(64)  NOT NULL,
    key_prefix    varchar(16)  NOT NULL,
    key_hash      varchar(64)  NOT NULL,
    created_at    timestamptz  NOT NULL,
    last_used_at  timestamptz,
    revoked_at    timestamptz,
    CONSTRAINT uk_agent_keys_prefix UNIQUE (key_prefix)
);

CREATE INDEX idx_agent_keys_owner ON agent_keys (owner_user_id);
